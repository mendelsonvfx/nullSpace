use std::process::Command;
use std::time::Duration;
use serde::{Deserialize, Serialize};

// Embedded at compile time via UPDATE_TOKEN env var (set in GitHub Actions).
// None in local dev builds → update check silently returns Ok(None).
// Some("") if Actions secret is missing → treated as None (see token guard below).
const GITHUB_TOKEN: Option<&str> = option_env!("UPDATE_TOKEN");

#[derive(Deserialize)]
struct GithubAsset {
    name: String,
    url: String,
    browser_download_url: String, // direct github.com URL — redirects to S3 pre-signed URL
}

#[derive(Deserialize)]
struct GithubRelease {
    tag_name: String,           // e.g. "v1.7.4"
    body: Option<String>,       // release notes in Markdown (auto-generated by softprops)
    html_url: String,           // GitHub release page URL
    published_at: Option<String>, // ISO 8601 UTC
    assets: Vec<GithubAsset>,
}

#[derive(Serialize)]
pub struct UpdateInfo {
    pub version: String,
    pub download_url: String,
    pub notes: Option<String>,
    pub release_url: Option<String>,
    pub pub_date: Option<String>,
}

#[tauri::command]
pub async fn check_for_update(app_handle: tauri::AppHandle) -> Result<Option<UpdateInfo>, String> {
    // Guard: token must be present and non-empty.
    // option_env! returns None if env var unset, Some("") if Actions secret missing.
    let token = match GITHUB_TOKEN {
        Some(t) if !t.is_empty() => t,
        _ => return Ok(None),
    };

    let current = app_handle.package_info().version.to_string();

    // 10-second timeout matches existing reqwest usage pattern in the codebase
    let client = reqwest::Client::builder()
        .timeout(Duration::from_secs(10))
        .user_agent("nullSpace-updater/1.0")
        .build()
        .map_err(|e| e.to_string())?;

    let release: GithubRelease = client
        .get("https://api.github.com/repos/mendelsonvfx/nullSpace/releases/latest")
        .header("Authorization", format!("Bearer {}", token))
        .header("Accept", "application/vnd.github+json")
        .send()
        .await
        .map_err(|e| e.to_string())?
        .error_for_status() // returns Err on 4xx/5xx (e.g. 401 expired token, 404 no releases)
        .map_err(|e| e.to_string())?
        .json()
        .await
        .map_err(|e| e.to_string())?;

    let version = release.tag_name.trim_start_matches('v').to_string();

    if is_newer_version(&version, &current) {
        // Find nullSpace.exe asset — case-insensitive to handle any capitalisation
        let asset = release
            .assets
            .iter()
            .find(|a| a.name.eq_ignore_ascii_case("nullspace.exe"))
            .ok_or_else(|| "No Windows exe asset found in release".to_string())?;

        Ok(Some(UpdateInfo {
            version,
            download_url: asset.browser_download_url.clone(), // redirects to S3 pre-signed URL
            notes: release.body,
            release_url: Some(release.html_url),
            pub_date: release.published_at,
        }))
    } else {
        Ok(None)
    }
}

fn is_newer_version(latest: &str, current: &str) -> bool {
    let parse = |v: &str| -> [u64; 3] {
        let parts: Vec<&str> = v.trim_start_matches('v').split('.').collect();
        [
            parts.get(0).and_then(|s| s.parse().ok()).unwrap_or(0),
            parts.get(1).and_then(|s| s.parse().ok()).unwrap_or(0),
            parts.get(2).and_then(|s| s.parse().ok()).unwrap_or(0),
        ]
    };
    parse(latest) > parse(current)
}

#[tauri::command]
pub async fn install_portable_update(download_url: String) -> Result<(), String> {
    // Token guard — install_portable_update is only reachable after check_for_update
    // returned Some(...), which requires a valid token. This is a safety net.
    let token = match GITHUB_TOKEN {
        Some(t) if !t.is_empty() => t,
        _ => return Err("No update token configured".to_string()),
    };

    let current_exe = std::env::current_exe().map_err(|e| e.to_string())?;
    let temp_dir = std::env::temp_dir();
    let new_exe = temp_dir.join("nullspace_new.exe");

    // Download new exe — 5-minute timeout for large file download.
    // download_url is the GitHub API asset URL. GitHub responds with 302 to a
    // pre-signed CDN URL; reqwest follows the redirect automatically.
    // Authorization header is not forwarded to the CDN (different domain),
    // but the CDN URL is self-authenticated via query params — no auth needed there.
    let client = reqwest::Client::builder()
        .timeout(Duration::from_secs(300))
        .build()
        .map_err(|e| e.to_string())?;

    let bytes = client
        .get(&download_url)
        .header("Authorization", format!("Bearer {}", token))
        .send()
        .await
        .map_err(|e| e.to_string())?
        .error_for_status()
        .map_err(|e| e.to_string())?
        .bytes()
        .await
        .map_err(|e| e.to_string())?;

    // Sanity check: verify the downloaded bytes are a Windows PE executable.
    // If the token is expired, GitHub may redirect to an HTML login page (200 OK)
    // which error_for_status() would not catch. Writing HTML to disk and running
    // it as an exe causes a silent failure in the PowerShell replacement step.
    if bytes.len() < 2 || bytes[0] != 0x4D || bytes[1] != 0x5A {
        return Err("Downloaded file is not a valid Windows executable (MZ header missing)".to_string());
    }

    std::fs::write(&new_exe, &bytes).map_err(|e| e.to_string())?;

    let current_pid = std::process::id();
    // Escape single quotes in paths for PowerShell single-quoted strings
    let new_exe_str = new_exe.to_string_lossy().replace('\'', "''");
    let cur_exe_str = current_exe.to_string_lossy().replace('\'', "''");

    // PowerShell script:
    // - Start-Sleep 1s upfront ensures app window is gone before copy begins
    // - Wait-Process uses event-based handle waiting (not PID polling) — immune to PID reuse
    // - -ErrorAction SilentlyContinue handles the case the process already exited
    // - Start-Sleep 2s after wait: Windows Defender real-time scan holds exe lock
    //   for up to 1-2s post-exit; 500ms was insufficient, 2s is reliable
    // - try/catch with -ErrorAction Stop: if Copy-Item fails, Start-Process is NOT run
    //   (avoids launching a partially-written/corrupted exe if the copy failed mid-write)
    // - In Rust format!, {{ and }} produce literal { and } in the output string
    let ps_command = format!(
        "Start-Sleep -Seconds 1; \
         Wait-Process -Id {pid} -ErrorAction SilentlyContinue; \
         Start-Sleep -Seconds 2; \
         try {{ Copy-Item -Path '{new}' -Destination '{cur}' -Force -ErrorAction Stop; \
         Start-Process '{cur}' }} catch {{}}",
        pid = current_pid,
        new = new_exe_str,
        cur = cur_exe_str,
    );

    // CommandExt is a local use to enable .creation_flags() on Windows
    // CREATE_NO_WINDOW (0x08000000) prevents a console window from flashing on screen
    use std::os::windows::process::CommandExt;

    Command::new("powershell")
        .args(["-WindowStyle", "Hidden", "-Command", &ps_command])
        .creation_flags(0x08000000)
        .spawn()
        .map_err(|e| e.to_string())?;

    // std::process::exit has return type `!` (diverging) — no Ok(()) needed
    std::process::exit(0);
}
